"""Collect the frozen-design results into docs/patent_evaluation/final_summary.json and FINAL_TABLES.md."""
import json
from pathlib import Path
OUT = Path(__file__).resolve().parents[1] / "docs/patent_evaluation"
SHOW = ["adaptive", "frozen", "rollback", "cusum_r", "guard_cal", "cal_ledger", "full", "dual_noledger", "dual"]
NAMES = {"adaptive": "Adaptive baseline", "frozen": "Frozen baseline", "rollback": "Rollback", "cusum_r": "Clipped CUSUM",
         "guard_cal": "Calibrated bound guard", "cal_ledger": "Bound guard + ledger", "full": "CUSUM trigger + validated ref + ledger",
         "dual_noledger": "Dual trigger, no ledger", "dual": "Dual trigger + validated ref + ledger (proposed)"}
DATA = [("nab_dev", "NAB development (AWS CloudWatch, day-resampled; synthetic order)"), ("cs_dev", "CoreStack development (real Azure telemetry)"),
        ("nab_fresh", "NAB fresh (22 series from other categories, never run before)"), ("cs_fresh", "CoreStack fresh (22 resources never run before)")]


def f(x, pct=True):
    if x is None:
        return "-"
    return f"{100*x['rate']:.0f}% ({100*x['lo']:.0f}-{100*x['hi']:.0f})" if pct else str(x)


def main():
    summ, md = {}, ["# Frozen-design results (generated by evaluation/final_summary.py)\n",
                    "Rates are shares with a 95% interval from a bootstrap that resamples whole source series. Operating point: thresholds frozen from the "
                    "development sets so that stable, ambient-free development entities false-alert at <=5%. FPR = alerts on entities whose own data never moves "
                    "by 1 hour-scale unit. Stealth/fast/local = injected attacks (1/2/3 sigma over a long ramp; 4 sigma over 10 days; 4 sigma in business hours only).\n"]
    for ds, title in DATA:
        R = json.load(open(OUT / f"final_results_{ds}_0.05.json"))
        summ[ds] = {k: R[k] for k in ("n_entities", "n_sources", "n_clean_entities", "n_clean_sources", "n_shifted_entities", "n_shifted_sources", "thresholds")}
        summ[ds]["strategies"] = {}
        md.append(f"\n## {title}\n\nentities {R['n_entities']} from {R['n_sources']} series; clean (stable, ambient-free) {R['n_clean_entities']} from {R['n_clean_sources']} series; "
                  f"series with real shifts >=1 sigma {R['n_shifted_entities']} from {R['n_shifted_sources']} series.\n")
        md.append("| strategy | false alerts | 1σ | 2σ | 3σ | fast 4σ | local 4σ | poisoned calib. | silent displacement 2σ (median / p90) | legit. growth flagged → unresolved | real shifts flagged → unresolved |")
        md.append("|---|---|---|---|---|---|---|---|---|---|---|")
        for lab in SHOW:
            s = R["strategies"][lab]
            d = s["disp_stealth2.0"]
            real = "-" if "real_shift_flagged" not in s else f"{f(s['real_shift_flagged'])} → {f(s['real_shift_unresolved_of_flagged'])}"
            md.append(f"| {NAMES[lab]} | {f(s['fpr'])} | {f(s['tpr_stealth1.0'])} | {f(s['tpr_stealth2.0'])} | {f(s['tpr_stealth3.0'])} | {f(s['tpr_fast4'])} | {f(s['tpr_local4'])} | "
                      f"{f(s['tpr_poisoned'])} | {d['median']:.2f} / {d['p90']:.2f}σ | {f(s['benign_flagged'])} → {f(s['benign_unresolved_of_flagged'])} | {real} |")
            summ[ds]["strategies"][lab] = {k: s[k] for k in s if k in ("fpr", "tpr_stealth1.0", "tpr_stealth2.0", "tpr_stealth3.0", "tpr_fast4", "tpr_local4", "tpr_poisoned",
                                                                      "disp_stealth2.0", "disp_stealth3.0", "disp_fast4", "absorbed_stealth3", "benign_flagged",
                                                                      "benign_unresolved_of_flagged", "real_shift_flagged", "real_shift_unresolved_of_flagged")}
    md.append("\n## Absorption after the first alert (3σ stealth attack) and resolution of legitimate shifts\n")
    md.append("Share of the injected shift held in the stored baseline N days after each strategy's own first alert (median / p90), and share of flagged legitimate shifts "
              "with no hold or alert in the 14 days from day N. Same frozen thresholds.\n")
    summ["absorption"] = {}
    for ds, title in DATA:
        A = json.load(open(OUT / f"absorb_compare_{ds}.json"))
        summ["absorption"][ds] = A
        md.append(f"\n### {title}\n\n| strategy | attack +14d | attack +30d | attack +60d | legit. resolved +14d | +30d | +60d |\n|---|---|---|---|---|---|---|")
        for lab in ["adaptive", "longwin", "clip", "rollback", "cusum_r", "frozen", "dual_noledger", "dual"]:
            a = A[lab]
            def at(o):
                x = a[str(o)]["attack_share_median"]
                return "-" if x is None else f"{x:.2f} / {a[str(o)]['attack_share_p90']:.2f}"
            def rs(o):
                x = a[str(o)]["benign_resolved"]
                return "-" if x is None else f"{100*x:.0f}%"
            md.append(f"| {NAMES.get(lab, lab)} | {at(14)} | {at(30)} | {at(60)} | {rs(14)} | {rs(30)} | {rs(60)} |")
    (OUT / "final_summary.json").write_text(json.dumps(summ, indent=1))
    (OUT / "FINAL_TABLES.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


main()
